package io.github.kkrampis.clipharbor.transcribe

import android.content.Context
import android.content.pm.ServiceInfo
import android.net.Uri
import android.os.Build
import androidx.core.app.NotificationCompat
import androidx.work.CoroutineWorker
import androidx.work.ForegroundInfo
import androidx.work.WorkerParameters
import io.github.kkrampis.clipharbor.App
import io.github.kkrampis.clipharbor.container
import io.github.kkrampis.clipharbor.data.TranscriptStatus
import io.github.kkrampis.clipharbor.download.HttpFetch
import io.github.kkrampis.clipharbor.ui.components.friendlyError
import io.github.kkrampis.clipharbor.yt.BROWSER_USER_AGENT
import io.github.kkrampis.clipharbor.yt.Quality
import io.github.kkrampis.clipharbor.yt.YouTube
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.Request
import org.json.JSONObject
import org.vosk.LibVosk
import org.vosk.LogLevel
import org.vosk.Model
import org.vosk.Recognizer
import java.io.File
import java.io.IOException

/** Produces a transcript, either from YouTube's captions or by speech recognition on the phone. */
class TranscribeWorker(context: Context, params: WorkerParameters) : CoroutineWorker(context, params) {

    private val c get() = applicationContext.container
    private val dao get() = c.db.transcripts()
    private var lastWrite = 0L

    override suspend fun doWork(): Result {
        val url = inputData.getString(KEY_URL) ?: return Result.failure()
        val mode = inputData.getString(KEY_MODE) ?: return Result.failure()
        val language = inputData.getString(KEY_LANGUAGE) ?: ""
        val entity = dao.get(url) ?: return Result.failure()
        runCatching { setForeground(foreground(entity.title, -1)) }

        return try {
            val text = if (mode == MODE_CAPTIONS) {
                captions(url, language, inputData.getBoolean(KEY_AUTO, false))
            } else {
                onDevice(url, language)
            }
            if (text.isBlank()) error("No speech was recognized in this video")
            val latest = dao.get(url) ?: return Result.success() // removed while running
            dao.upsert(
                latest.copy(
                    text = text,
                    status = TranscriptStatus.DONE,
                    progress = 1f,
                    error = null,
                    updatedAt = System.currentTimeMillis(),
                ),
            )
            Result.success()
        } catch (e: CancellationException) {
            throw e
        } catch (e: Throwable) {
            dao.setStatus(url, TranscriptStatus.FAILED, friendlyError(e))
            Result.failure()
        } finally {
            File(applicationContext.cacheDir, "transcribe-${url.hashCode()}").deleteRecursively()
        }
    }

    private suspend fun captions(url: String, languageTag: String, auto: Boolean): String {
        dao.setProgress(url, TranscriptStatus.TRANSCRIBING, 0f)
        // Caption URLs expire, so they are looked up fresh.
        val tracks = YouTube.stream(url).captions
        val track = tracks.firstOrNull { it.languageTag == languageTag && it.autoGenerated == auto }
            ?: tracks.firstOrNull { it.languageTag == languageTag }
            ?: error("These captions are no longer available")
        val vtt = withContext(Dispatchers.IO) {
            val req = Request.Builder().url(track.url).header("User-Agent", BROWSER_USER_AGENT).build()
            c.http.newCall(req).execute().use { resp ->
                if (!resp.isSuccessful) throw IOException("YouTube refused the captions (HTTP ${resp.code})")
                resp.body?.string().orEmpty()
            }
        }
        return Vtt.toTranscript(vtt)
    }

    private suspend fun onDevice(url: String, modelId: String): String {
        val model = SpeechModels.byId(modelId) ?: error("Unknown speech model")
        val entity = dao.get(url)

        // 1. The speech model (downloaded once, then reused offline).
        dao.setProgress(url, TranscriptStatus.MODEL, 0f)
        val modelDir = SpeechModels.ensure(applicationContext, c.http, model) { p ->
            throttled(url, TranscriptStatus.MODEL, p, entity?.title)
        }

        // 2. The audio: a finished download if there is one, otherwise the audio stream.
        val source: Uri = c.db.downloads().finishedFor(url)?.fileUri?.let(Uri::parse)
            ?: run {
                dao.setProgress(url, TranscriptStatus.AUDIO, 0f)
                val details = YouTube.stream(url)
                val audio = Quality.bestAudio(details.audio) ?: error("This video has no audio stream to transcribe")
                val dir = File(applicationContext.cacheDir, "transcribe-${url.hashCode()}").apply { mkdirs() }
                val file = File(dir, "audio.m4a")
                val total = HttpFetch.contentLength(c.http, audio.content)
                var done = 0L
                HttpFetch.download(c.http, audio.content, file) { n ->
                    done += n
                    if (total > 0) throttled(url, TranscriptStatus.AUDIO, done.toFloat() / total, entity?.title)
                }
                Uri.fromFile(file)
            }

        // 3. Speech recognition.
        dao.setProgress(url, TranscriptStatus.TRANSCRIBING, 0f)
        LibVosk.setLogLevel(LogLevel.WARNINGS)
        val builder = TranscriptBuilder()
        withContext(Dispatchers.Default) {
            Model(modelDir.absolutePath).use { voskModel ->
                Recognizer(voskModel, AudioDecoder.SAMPLE_RATE.toFloat()).use { rec ->
                    rec.setWords(true)
                    val pending = ShortArray(AudioDecoder.SAMPLE_RATE / 2)
                    var filled = 0
                    var fedSamples = 0L
                    fun feed(buf: ShortArray, len: Int) {
                        if (rec.acceptWaveForm(buf, len)) addResult(builder, rec.result, fedSamples)
                        fedSamples += len
                    }
                    AudioDecoder.decode(
                        applicationContext,
                        source,
                        onProgress = { p -> throttled(url, TranscriptStatus.TRANSCRIBING, p, entity?.title) },
                    ) { chunk, len ->
                        var off = 0
                        while (off < len) {
                            val n = minOf(len - off, pending.size - filled)
                            System.arraycopy(chunk, off, pending, filled, n)
                            filled += n
                            off += n
                            if (filled == pending.size) {
                                feed(pending, filled)
                                filled = 0
                            }
                        }
                    }
                    if (filled > 0) feed(pending, filled)
                    addResult(builder, rec.finalResult, fedSamples)
                }
            }
        }
        return builder.toString()
    }

    /** Adds one recognizer result; uses word timings when present, else the audio position. */
    private fun addResult(builder: TranscriptBuilder, json: String, fedSamples: Long) {
        val o = runCatching { JSONObject(json) }.getOrNull() ?: return
        val text = o.optString("text")
        if (text.isBlank()) return
        val first = o.optJSONArray("result")?.optJSONObject(0)
        val start = if (first != null && first.has("start")) {
            first.optDouble("start")
        } else {
            fedSamples.toDouble() / AudioDecoder.SAMPLE_RATE
        }
        builder.add(start, text)
    }

    private suspend fun throttled(url: String, status: String, progress: Float, title: String?) {
        val now = System.currentTimeMillis()
        if (now - lastWrite < 800) return
        lastWrite = now
        dao.setProgress(url, status, progress.coerceIn(0f, 1f))
        runCatching { setForeground(foreground(title ?: "Transcript", (progress * 100).toInt())) }
    }

    private fun foreground(title: String, percent: Int): ForegroundInfo {
        val notification = NotificationCompat.Builder(applicationContext, App.DOWNLOAD_CHANNEL)
            .setSmallIcon(android.R.drawable.ic_btn_speak_now)
            .setContentTitle(title)
            .setContentText(if (percent >= 0) "Making transcript · $percent%" else "Making transcript")
            .setProgress(100, percent.coerceAtLeast(0), percent < 0)
            .setOngoing(true)
            .setOnlyAlertOnce(true)
            .build()
        val notificationId = 50_000 + (this.id.hashCode() and 0xFFFF)
        return if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
            ForegroundInfo(notificationId, notification, ServiceInfo.FOREGROUND_SERVICE_TYPE_DATA_SYNC)
        } else {
            ForegroundInfo(notificationId, notification)
        }
    }

    companion object {
        const val KEY_URL = "url"
        const val KEY_MODE = "mode"
        const val KEY_LANGUAGE = "language"
        const val KEY_AUTO = "auto"
        const val MODE_CAPTIONS = "captions"
        const val MODE_DEVICE = "device"
    }
}
