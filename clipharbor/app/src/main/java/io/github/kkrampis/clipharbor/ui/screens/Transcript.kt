class TranscriptViewModel(app: Application, val url: String, initialTitle: String) : AndroidViewModel(app) {
    private val repo = app.container.transcripts

    val transcript = repo.observe(url).stateIn(viewModelScope, SharingStarted.WhileSubscribed(5000), null)

    var title by mutableStateOf(initialTitle)
        private set
    var captions by mutableStateOf<List<CaptionTrack>>(emptyList())
        private set
    var captionsLoading by mutableStateOf(true)
        private set
    var captionsError by mutableStateOf<String?>(null)
        private set

    init {
        viewModelScope.launch {
            try {
                val d = YouTube.stream(url)
                if (title.isBlank()) title = d.video.title
                captions = d.captions
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                captionsError = friendlyError(e)
            } finally {
                captionsLoading = false
            }
        }
    }

    fun useCaptions(track: CaptionTrack) = viewModelScope.launch {
        repo.fromCaptions(url, title, track.languageTag, track.autoGenerated)
    }

    fun transcribe(model: SpeechModel) = viewModelScope.launch { repo.onDevice(url, title, model.id) }

    fun discard() = viewModelScope.launch { repo.delete(url) }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun TranscriptScreen(url: String, title: String, onBack: () -> Unit) {
    val app = LocalContext.current.applicationContext as Application
    val vm: TranscriptViewModel = viewModel(key = "transcript:$url") { TranscriptViewModel(app, url, title) }
    val t by vm.transcript.collectAsState()

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Transcript") },
                navigationIcon = {
                    IconButton(onClick = onBack) { Icon(Icons.AutoMirrored.Filled.ArrowBack, "Back") }
                },
                actions = {
                    val current = t
                    if (current != null && !TranscriptStatus.isActive(current.status)) {
                        IconButton(onClick = { vm.discard() }) { Icon(Icons.Default.Refresh, "Make a new transcript") }
                    }
                },
            )
        },
    ) { pad ->
        val current = t
        Column(Modifier.padding(pad).fillMaxSize()) {
            Text(
                vm.title,
                style = MaterialTheme.typography.titleMedium,
                modifier = Modifier.padding(horizontal = 16.dp, vertical = 8.dp),
            )
            when {
                current == null -> SourcePicker(vm)
                current.status == TranscriptStatus.DONE -> TranscriptView(current, vm.title)
                current.status == TranscriptStatus.FAILED -> Column {
                    Text(
                        "That didn't work: ${current.error ?: "unknown error"}",
                        color = MaterialTheme.colorScheme.error,
                        modifier = Modifier.padding(horizontal = 16.dp),
                    )
                    SourcePicker(vm)
                }
                else -> Working(current, onCancel = { vm.discard() })
            }
        }
    }
}

@Composable
private fun Working(t: TranscriptEntity, onCancel: () -> Unit) {
    val stage = when (t.status) {
        TranscriptStatus.QUEUED -> "Waiting to start"
        TranscriptStatus.MODEL -> "Downloading the speech model (only needed once)"
        TranscriptStatus.AUDIO -> "Downloading the audio"
        TranscriptStatus.TRANSCRIBING ->
            if (t.source == TranscribeWorker.MODE_CAPTIONS) "Fetching captions" else "Listening and transcribing on this phone"
        else -> t.status
    }
    Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {
        Text("$stage · ${(t.progress * 100).toInt()}%")
        if (t.progress > 0f) {
            LinearProgressIndicator(progress = { t.progress }, modifier = Modifier.fillMaxWidth())
        } else {
            LinearProgressIndicator(Modifier.fillMaxWidth())
        }
        Text(
            "You can leave this screen. It keeps going in the background.",
            style = MaterialTheme.typography.bodySmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
        TextButton(onClick = onCancel) { Text("Cancel") }
    }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
private fun SourcePicker(vm: TranscriptViewModel) {
    val context = LocalContext.current
    LazyColumn(
        Modifier.fillMaxSize(),
        contentPadding = PaddingValues(16.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp),
    ) {
        item {
            Card(Modifier.fillMaxWidth()) {
                Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                    Text("YouTube captions", style = MaterialTheme.typography.titleMedium)
                    Text(
                        "Fastest. Uses the subtitles the video already has.",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                    when {
                        vm.captionsLoading -> LinearProgressIndicator(Modifier.fillMaxWidth())
                        vm.captionsError != null -> Text(vm.captionsError!!, color = MaterialTheme.colorScheme.error)
                        vm.captions.isEmpty() -> Text("This video has no captions. Transcribe it on the phone instead.")
                        else -> vm.captions.forEach { track ->
                            OutlinedButton(onClick = { vm.useCaptions(track) }, modifier = Modifier.fillMaxWidth()) {
                                Text(track.label)
                            }
                        }
                    }
                }
            }
        }
        item {
            Card(Modifier.fillMaxWidth()) {
                Column(Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                    Text("Transcribe on this phone", style = MaterialTheme.typography.titleMedium)
                    Text(
                        "Listens to the audio with an offline speech model, so nothing is sent anywhere. " +
                            "The model for each language downloads once. Uses a finished download of this video if " +
                            "you have one, otherwise fetches just the audio. Takes a while on long videos.",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                    var expanded by remember { mutableStateOf(false) }
                    val default = remember {
                        val lang = Locale.getDefault().language
                        SpeechModels.all.firstOrNull { it.id == lang } ?: SpeechModels.all.first()
                    }
                    var model by remember { mutableStateOf(default) }
                    ExposedDropdownMenuBox(expanded = expanded, onExpandedChange = { expanded = it }) {
                        OutlinedTextField(
                            value = modelLabel(context, model),
                            onValueChange = {},
                            readOnly = true,
                            label = { Text("Spoken language") },
                            trailingIcon = { ExposedDropdownMenuDefaults.TrailingIcon(expanded) },
                            modifier = Modifier
                                .fillMaxWidth()
                                .menuAnchor(MenuAnchorType.PrimaryNotEditable),
                        )
                        ExposedDropdownMenu(
                            expanded = expanded,
                            onDismissRequest = { expanded = false },
                        ) {
                            SpeechModels.all.forEach { m ->
                                DropdownMenuItem(
                                    text = { Text(modelLabel(context, m)) },
                                    onClick = {
                                        model = m
                                        expanded = false
                                    },
                                )
                            }
                        }
                    }
                    Button(onClick = { vm.transcribe(model) }, modifier = Modifier.fillMaxWidth()) {
                        Text("Transcribe")
                    }
                }
            }
        }
    }
}

private fun modelLabel(context: Context, m: SpeechModel): String =
    if (SpeechModels.isInstalled(context, m)) "${m.language} · downloaded" else m.label

@Composable
private fun TranscriptView(t: TranscriptEntity, title: String) {
    val context = LocalContext.current
    var prompt by rememberSaveable { mutableStateOf(AiPrompt.SUMMARY) }
    val claude = remember { TranscriptShare.isClaudeInstalled(context) }
    val payload = { TranscriptShare.compose(title, t.url, t.text, prompt) }

    LazyColumn(Modifier.fillMaxSize()) {
        item {
            Column(Modifier.padding(horizontal = 16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                val source = if (t.source == TranscribeWorker.MODE_CAPTIONS) {
                    "From YouTube captions (${t.language})"
                } else {
                    "Transcribed on this phone (${SpeechModels.byId(t.language)?.language ?: t.language})"
                }
                Text(source, style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                Text("Send to an AI app with:", style = MaterialTheme.typography.labelLarge)
                LazyRow(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    items(AiPrompt.entries) { p ->
                        FilterChip(selected = p == prompt, onClick = { prompt = p }, label = { Text(p.label) })
                    }
                }
                LazyRow(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    if (claude) {
                        item {
                            AssistChip(
                                onClick = { TranscriptShare.toClaude(context, title, payload()) },
                                label = { Text("Claude") },
                                leadingIcon = {
                                    Icon(Icons.AutoMirrored.Filled.Send, null, Modifier.size(AssistChipDefaults.IconSize))
                                },
                            )
                        }
                    }
                    item {
                        AssistChip(
                            onClick = { TranscriptShare.shareText(context, title, payload()) },
                            label = { Text(if (claude) "Other app" else "Share to AI app") },
                            leadingIcon = { Icon(Icons.Default.Share, null, Modifier.size(AssistChipDefaults.IconSize)) },
                        )
                    }
                    item {
                        AssistChip(
                            onClick = { TranscriptShare.shareFile(context, title, payload()) },
                            label = { Text(".txt file") },
                            leadingIcon = {
                                Icon(Icons.Default.Description, null, Modifier.size(AssistChipDefaults.IconSize))
                            },
                        )
                    }
                    item {
                        AssistChip(
                            onClick = {
                                val cm = context.getSystemService(ClipboardManager::class.java)
                                cm.setPrimaryClip(ClipData.newPlainText("Transcript", payload()))
                                Toast.makeText(context, "Copied", Toast.LENGTH_SHORT).show()
                            },
                            label = { Text("Copy") },
                            leadingIcon = {
                                Icon(Icons.Default.ContentCopy, null, Modifier.size(AssistChipDefaults.IconSize))
                            },
                        )
                    }
                }
            }
        }
        item {
            SelectionContainer {
                Text(
                    t.text,
                    style = MaterialTheme.typography.bodyMedium,
                    modifier = Modifier.padding(16.dp),
                )
            }
        }
    }
}
