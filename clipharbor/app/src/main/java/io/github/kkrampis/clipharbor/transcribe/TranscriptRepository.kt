package io.github.kkrampis.clipharbor.transcribe

import android.content.Context
import androidx.work.Constraints
import androidx.work.ExistingWorkPolicy
import androidx.work.NetworkType
import androidx.work.OneTimeWorkRequestBuilder
import androidx.work.WorkManager
import androidx.work.workDataOf
import io.github.kkrampis.clipharbor.data.AppDatabase
import io.github.kkrampis.clipharbor.data.TranscriptEntity
import io.github.kkrampis.clipharbor.data.TranscriptStatus
import kotlinx.coroutines.flow.Flow

class TranscriptRepository(private val context: Context, db: AppDatabase) {
    private val dao = db.transcripts()
    private val work get() = WorkManager.getInstance(context)

    fun observe(url: String): Flow<TranscriptEntity?> = dao.observe(url)

    /** Fetches YouTube's captions in [languageTag]. */
    suspend fun fromCaptions(url: String, title: String, languageTag: String, autoGenerated: Boolean) =
        start(url, title, TranscribeWorker.MODE_CAPTIONS, languageTag, autoGenerated, needsNetwork = true)

    /** Runs offline speech recognition with the given model on the video's audio. */
    suspend fun onDevice(url: String, title: String, modelId: String) =
        start(url, title, TranscribeWorker.MODE_DEVICE, modelId, false, needsNetwork = false)

    private suspend fun start(
        url: String,
        title: String,
        mode: String,
        language: String,
        auto: Boolean,
        needsNetwork: Boolean,
    ) {
        dao.upsert(
            TranscriptEntity(
                url = url,
                title = title,
                source = mode,
                language = language,
                text = "",
                status = TranscriptStatus.QUEUED,
                progress = 0f,
                error = null,
                updatedAt = System.currentTimeMillis(),
            ),
        )
        val constraints = Constraints.Builder()
            .setRequiredNetworkType(if (needsNetwork) NetworkType.CONNECTED else NetworkType.NOT_REQUIRED)
            .build()
        val request = OneTimeWorkRequestBuilder<TranscribeWorker>()
            .setInputData(
                workDataOf(
                    TranscribeWorker.KEY_URL to url,
                    TranscribeWorker.KEY_MODE to mode,
                    TranscribeWorker.KEY_LANGUAGE to language,
                    TranscribeWorker.KEY_AUTO to auto,
                ),
            )
            .setConstraints(constraints)
            .build()
        work.enqueueUniqueWork(workName(url), ExistingWorkPolicy.REPLACE, request)
    }

    suspend fun cancel(url: String) {
        work.cancelUniqueWork(workName(url))
        dao.delete(url)
    }

    suspend fun delete(url: String) {
        work.cancelUniqueWork(workName(url))
        dao.delete(url)
    }

    private fun workName(url: String) = "transcript-" + url.hashCode()
}
